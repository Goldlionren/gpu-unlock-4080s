static const int ad_cases[]={
 SUCCESS,FWSEC_TIMEOUT,POST_FLR_TIMEOUT,BME_READBACK_FAIL,MMIO_WRITE_FAIL,
 FLUSH_FAIL,FLR_WRITE_FAIL,UNMAP_FAIL,MAP_FAIL,MAP_PARTIAL,RESTORE_FAIL,
 DISPLAY_CHANGED,SELECTOR_LOST,FWSEC_NO_WPR,FWSEC_RUNNING,DIAG_READ_FAIL,
 POST_DIAG_READ_FAIL,PIO_UNAVAILABLE,PIO_UNAVAILABLE_NO_WPR,FWSEC_ERROR_CODE,
 SEC2_DELAYED_START,SEC2_STUCK_HALT,SEC2_RUN_HALT,SEC2_RUN_TIMEOUT,
 SEC2_UNAVAILABLE,SEC2_DIAG_FAIL,SEC2_PROTECTED_DIAG,SEC2_STATUS_ERROR_PLM_OPEN,
 PLM_SECOND_TARGET_TIMEOUT,PLM_PRIOR_RELOCK,PLM_WRONG_WPR_CFG_MASK,
 PLM_PREOPEN_SKIP,PLM_TARGET_READ_FAILURE,RESET_CHANGES_WPR_FIRST,
 RESET_CORRUPTS_PAYLOAD_FIRST,
 AD_MARKER_MISSING,AD_MARKER_WRONG,AD_MARKER_NO_OPEN,
 AD_THIRD_FAIL,AD_FEAT_FAIL,AD_SS0_REJECT,AD_SS1_REJECT,AD_FBPA_REJECT
};
static BOOLEAN ad_success(int mode) {
 return mode==SUCCESS || mode==FWSEC_RUNNING || mode==PIO_UNAVAILABLE ||
        mode==SEC2_DELAYED_START || mode==PLM_PREOPEN_SKIP || mode==AD_FBPA_REJECT;
}
static BOOLEAN ad_before_selectors(int mode) {
 return !ad_success(mode) && mode!=POST_FLR_TIMEOUT && mode!=FLR_WRITE_FAIL &&
        mode!=UNMAP_FAIL && mode!=RESTORE_FAIL && mode!=DISPLAY_CHANGED &&
        mode!=SELECTOR_LOST && mode!=AD_SS0_REJECT && mode!=AD_SS1_REJECT;
}
